const PRODUCTS_STORAGE_KEY = 'buybright_admin_products_v2';

export function getProducts(): AdminProduct[] {
  try {
    const raw = localStorage.getItem(PRODUCTS_STORAGE_KEY);
    if (raw) return JSON.parse(raw) as AdminProduct[];
  } catch {
    // fallback to initial mock data
  }
  return initialProductsData;
}

export function saveProducts(products: AdminProduct[]): void {
  try {
    localStorage.setItem(PRODUCTS_STORAGE_KEY, JSON.stringify(products));
  } catch {
    // silent fail
  }
}

export function getProductById(id: string): AdminProduct | null {
  return getProducts().find((p) => p.id === id) ?? null;
}

