const BRANDS_STORAGE_KEY = 'buybright_admin_brands_v3';

export function getBrands(): AdminBrand[] {
  try {
    const raw = localStorage.getItem(BRANDS_STORAGE_KEY);
    if (raw) return JSON.parse(raw) as AdminBrand[];
  } catch {
    // fallback
  }
  return initialBrandsData;
}

export function saveBrands(brands: AdminBrand[]): void {
  try {
    localStorage.setItem(BRANDS_STORAGE_KEY, JSON.stringify(brands));
  } catch {
    // silent fail
  }
}

export function getBrandById(id: string): AdminBrand | null {
  return getBrands().find((b) => b.id === id) ?? null;
}
