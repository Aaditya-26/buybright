const ORDERS_STORAGE_KEY = 'prestodental_admin_orders_v2';

export function getOrders(): AdminOrder[] {
  try {
    const raw = localStorage.getItem(ORDERS_STORAGE_KEY);
    if (raw) return JSON.parse(raw) as AdminOrder[];
  } catch {
    // fallback
  }
  return initialOrdersData;
}

export function saveOrders(orders: AdminOrder[]): void {
  try {
    localStorage.setItem(ORDERS_STORAGE_KEY, JSON.stringify(orders));
  } catch {
    // silent fail
  }
}

export function getOrderById(id: string): AdminOrder | null {
  return getOrders().find((o) => o.id === id) ?? null;
}

export function updateOrderStatus(orderId: string, newStatus: OrderStatusType): AdminOrder[] {
  const current = getOrders();
  const updated = current.map((o) => (o.id === orderId ? { ...o, orderStatus: newStatus } : o));
  saveOrders(updated);
  return updated;
}
